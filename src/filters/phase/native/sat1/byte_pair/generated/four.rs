    fn byte_pair_four_bank_producer_binds_native_precision_and_shared_roles() {
        let mut normal = alloc::vec![255;0x220000];
        let at = (REFERENCE - 0x410000) as usize;
        normal[at..at + CODE.len()].copy_from_slice(CODE);
        let eval_at = (0x57a24a - 0x410000) as usize;
        normal[eval_at..eval_at + EVALUATORS.len()].copy_from_slice(EVALUATORS);
        for (address, text) in [
            (0x5fc94a, b"SL1+:%02xh\n\0"),
            (0x5fc956, b"SL1-:%02xh\n\0"),
            (0x5fc962, b"SL2+:%02xh\n\0"),
            (0x5fc96e, b"SL2-:%02xh\n\0"),
        ] {
            let start = address - 0x410000;
            normal[start..start + text.len()].copy_from_slice(text);
        }
        let binding = Binding {
            shape: 8,
            body: 0x1000..0x109c,
            command: None,
            complete_command: true,
            coefficients: [0x4312, 0x4392, 0x4412, 0x4492]
                .into_iter()
                .map(Coefficients::Ram)
                .collect(),
            state: alloc::vec![],
            output_leaf: None,
        };
        let graph = observe(&normal, &binding).unwrap();
        assert_eq!(graph.producer.len(), 1268);
        assert_eq!(graph.evaluators.unwrap().precision, shared::Precision::Byte);
        let &(offset, width, _) = FIELDS
            .iter()
            .find(|(_, _, reference)| *reference == 0x405a14)
            .unwrap();
        normal[at + offset + width - 1] ^= 2;
        assert_eq!(observe(&normal, &binding), Err(Error::Unresolved));
        normal[at + offset + width - 1] ^= 2;
        let mut mismatched = binding.clone();
        mismatched.coefficients[3] = Coefficients::Ram(0x4512);
        assert_eq!(observe(&normal, &mismatched), Err(Error::Unresolved));
    }
