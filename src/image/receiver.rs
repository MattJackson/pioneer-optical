/// Identify a unique supported Kernel finalizer from its code, independently of
/// the image's generation marker, marketing identity or firmware catalog.
/// Unknown, truncated and ambiguous implementations return `None`.
/// This does not establish authentication, transfer routing or flash compatibility.
pub fn kernel_marker_policy(image: &[u8]) -> Option<KernelMarkerPolicy> {
    if image.len() != KERNEL_LEN {
        return None;
    }
    let mut found = None;
    for (template, policy) in [
        (UNGATED_FINALIZER, KernelMarkerPolicy::NoMarkerCheck),
        (GATED_FINALIZER, KernelMarkerPolicy::RejectZeroAndErased),
    ] {
        let calls: &[usize] = if policy == KernelMarkerPolicy::NoMarkerCheck {
            &[DECODER_CALL, CHECKSUM_CALL]
        } else {
            &[DECODER_CALL, CHECKSUM_CALL, MARKER_CALL]
        };
        for candidate in image.windows(template.len()).step_by(INSTRUCTION_ALIGNMENT) {
            if !candidate
                .iter()
                .zip(template)
                .enumerate()
                .all(|(i, (a, b))| {
                    calls
                        .iter()
                        .any(|c| (*c + 1..*c + 1 + CALL_ADDRESS_LEN).contains(&i))
                        || a == b
                })
                || !calls
                    .iter()
                    .all(|&c| call_target(image, candidate, c).is_some())
            {
                continue;
            }
            if policy == KernelMarkerPolicy::RejectZeroAndErased {
                let target = call_target(image, candidate, MARKER_CALL)?;
                let body = image.get(target..target.checked_add(MARKER_CHECK.len())?)?;
                if !body
                    .iter()
                    .zip(MARKER_CHECK)
                    .enumerate()
                    .all(|(i, (a, b))| {
                        (RECOVERY_FLAG_ADDRESS..RECOVERY_FLAG_ADDRESS + ADDRESS_LEN).contains(&i)
                            || a == b
                    })
                {
                    return None;
                }
            }
            if found.replace(policy).is_some() {
                return None;
            }
        }
    }
    for &(template, scratch) in LEGACY_FINALIZERS {
        for candidate in image.windows(template.len()).step_by(INSTRUCTION_ALIGNMENT) {
            let calls = [LEGACY_DECODER_CALL, LEGACY_COPY_CALL];
            let matched = candidate
                .iter()
                .zip(template)
                .enumerate()
                .all(|(i, (a, b))| {
                    (scratch..scratch + ADDRESS_LEN).contains(&i)
                        || calls
                            .iter()
                            .any(|c| (*c + 1..*c + 1 + CALL_ADDRESS_LEN).contains(&i))
                        || a == b
                });
            if !matched
                || calls
                    .iter()
                    .any(|&c| call_target(image, candidate, c).is_none())
            {
                continue;
            }
            if found.replace(KernelMarkerPolicy::NoMarkerCheck).is_some() {
                return None;
            }
        }
    }
    found
}

fn call_target(image: &[u8], candidate: &[u8], offset: usize) -> Option<usize> {
    let address = candidate.get(offset + 1..offset + 4)?;
    let address = u32::from_be_bytes([0, address[0], address[1], address[2]]);
    let offset = address.checked_sub(KERNEL_BASE)? as usize;
    if offset % INSTRUCTION_ALIGNMENT != 0 {
        return None;
    }
    image.get(offset..offset.checked_add(2)?)?;
    Some(offset)
}

