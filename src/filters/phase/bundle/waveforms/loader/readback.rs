fn value(bytes: &[u8], at: usize, width: usize) -> u32 {
    bytes[at..at + width]
        .iter()
        .fold(0, |n, b| (n << 8) | u32::from(*b))
}
fn stored(normal: &[u8], address: u32, size: usize) -> Result<Range<usize>, Error> {
    let start = address
        .checked_sub(0x410000)
        .ok_or(Error::ResourceMismatch)? as usize;
    let end = start.checked_add(size).ok_or(Error::ResourceMismatch)?;
    let regions = crate::image::regions(normal).ok_or(Error::Unresolved)?;
    if start & 1 != 0
        || !regions.stored.iter().any(|region| {
            let at = region.as_ptr() as usize - normal.as_ptr() as usize;
            start >= at && end <= at + region.len()
        })
    {
        return Err(Error::ResourceMismatch);
    }
    Ok(start..end)
}

/// Bind the reader to the exact writer selected by the loader.
/// No helper is copied or changed; both donor and target must satisfy this ABI.
pub fn observe(normal: &[u8], address: u32, writer_address: u32) -> Result<Binding, Error> {
    let writer = writer::observe(normal, writer_address)?;
    for (body, calls, shadow, clears) in [
        (REGISTERS, [69, 147], 46, &[][..]),
        (STACK, [111, 179], 90, &[23, 33][..]),
    ] {
        let Ok(program) = stored(normal, address, body.len()) else {
            continue;
        };
        let bytes = &normal[program.clone()];
        if !bytes.iter().zip(body).enumerate().all(|(i, (a, b))| {
            (shadow..shadow + 4).contains(&i)
                || calls
                    .iter()
                    .chain(clears)
                    .any(|at| (*at..*at + 3).contains(&i))
                || a == b
        }) {
            continue;
        }
        if value(bytes, shadow, 4) != writer.shadow
            || calls
                .iter()
                .any(|at| value(bytes, *at, 3) != writer_address)
        {
            return Err(Error::ResourceMismatch);
        }
        let clear = if let Some(at) = clears.first() {
            let helper = value(bytes, *at, 3);
            if clears.iter().any(|at| value(bytes, *at, 3) != helper) {
                return Err(Error::ResourceMismatch);
            }
            let span = stored(normal, helper, CLEAR.len())?;
            if &normal[span.clone()] != CLEAR {
                return Err(Error::ResourceMismatch);
            }
            Some(span)
        } else {
            None
        };
        return Ok(Binding { program, clear });
    }
    Err(Error::ResourceMismatch)
}
