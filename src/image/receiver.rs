/// Marker behavior at the recognized Kernel finalization step.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
#[non_exhaustive]
pub enum KernelMarkerPolicy {
    /// The recognized finalizer proceeds directly to the checksum check.
    NoMarkerCheck,
    /// The finalizer rejects markers zero and 0xff during ordinary operation.
    /// Its recovery-state exception does not authorize skipping validation.
    RejectZeroAndErased,
}

