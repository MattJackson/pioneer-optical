fn integer(bytes: &[u8]) -> u32 {
    bytes.iter().fold(0, |n, b| (n << 8) | u32::from(*b))
}
fn stored(normal: &[u8], at: usize, len: usize) -> bool {
    let Some(end) = at.checked_add(len) else {
        return false;
    };
    crate::image::regions(normal).is_some_and(|regions| {
        regions.stored.iter().any(|r| {
            let start = r.as_ptr() as usize - normal.as_ptr() as usize;
            at >= start && end <= start + r.len()
        })
    })
}
fn normalized(program: &[u8], normal_len: usize) -> Option<Vec<u8>> {
    if program.len() != PROGRAM.len() {
        return None;
    }
    let mut normalized = program.to_vec();
    let mut bindings = [vec![None; 8], vec![None; 5]];
    let mut cursor = 0;
    for &(at, width, kind, ordinal) in HOLES {
        if program[cursor..at] != PROGRAM[cursor..at] {
            return None;
        }
        let value = integer(&program[at..at + width]);
        if (kind == 0 && value >= 0x8000)
            || (kind == 1
                && (value < 0x400000
                    || value & 1 != 0
                    || u64::from(value) >= u64::from(BASE) + normal_len as u64))
        {
            return None;
        }
        let slots = &mut bindings[usize::from(kind)];
        if slots[ordinal].is_some_and(|previous| previous != value)
            || slots
                .iter()
                .enumerate()
                .any(|(i, previous)| i != ordinal && *previous == Some(value))
        {
            return None;
        }
        slots[ordinal] = Some(value);
        normalized[at..at + width]
            .copy_from_slice(&((ordinal + 1) as u32).to_be_bytes()[4 - width..]);
        cursor = at + width;
    }
    if program[cursor..] != PROGRAM[cursor..] {
        return None;
    }
    Some(normalized)
}
pub(super) fn discover(normal: &[u8]) -> Observation<Vec<u8>> {
    let missing = || Observation::Unresolved(Unresolved::ReaderNotRecognized);
    if !stored(normal, ENTRY, 4) {
        return missing();
    }
    let call = &normal[ENTRY..ENTRY + 4];
    if call[0] != 0x5e {
        return missing();
    }
    let target = integer(&call[1..]);
    let Some(at) = target.checked_sub(BASE).map(|v| v as usize) else {
        return missing();
    };
    if at & 1 != 0 || !stored(normal, at, PROGRAM.len()) {
        return missing();
    }
    match normalized(&normal[at..at + PROGRAM.len()], normal.len()) {
        Some(value) => Observation::Known(value),
        None => missing(),
    }
}
