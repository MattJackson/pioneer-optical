pub(super) fn bind(normal: &[u8], binding: &mut Binding) -> Result<(), Error> {
    let (grammar, fields) = match binding.shape {
        3 | 4 => (ROM_COMMAND, ROM_COMMAND_FIELDS),
        7 => (RAM_THREE_COMMAND, RAM_THREE_COMMAND_FIELDS),
        8 => (RAM_FOUR_COMMAND, RAM_FOUR_COMMAND_FIELDS),
        _ => return Ok(()),
    };
    let start = binding
        .body
        .start
        .checked_sub(grammar.len() + 6)
        .ok_or(Error::Unresolved)?;
    let range = stored(normal, 0x410000 + start as u32, grammar.len())?;
    let code = &normal[range.clone()];
    if !code
        .iter()
        .zip(grammar)
        .enumerate()
        .all(|(i, (a, b))| a == b || fields.iter().any(|at| (*at..*at + 4).contains(&i)))
    {
        return Err(Error::Unresolved);
    }
    let state = integer(&code[fields[0]..fields[0] + 4]);
    let direction = integer(&code[fields[1]..fields[1] + 4]);
    if state == 0
        || state.checked_add(18).map_or(true, |end| end >= 0x400000)
        || direction == 0
        || direction >= 0x400000
        || (state..state + 18).contains(&direction)
        || fields[2..]
            .iter()
            .any(|at| integer(&code[*at..*at + 4]) != direction)
    {
        return Err(Error::ResourceMismatch);
    }
    if matches!(binding.shape, 7 | 8)
        && binding.coefficients.first() != Some(&Coefficients::Ram(state + 38))
    {
        return Err(Error::ResourceMismatch);
    }
    binding.command = Some(range);
    binding.state = alloc::vec![state, direction];
    binding.complete_command = true;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn byte_pair_commands_bind_state_direction_and_output_edges() {
        for (shape, grammar, fields) in [
            (3, ROM_COMMAND, ROM_COMMAND_FIELDS),
            (4, ROM_COMMAND, ROM_COMMAND_FIELDS),
            (7, RAM_THREE_COMMAND, RAM_THREE_COMMAND_FIELDS),
            (8, RAM_FOUR_COMMAND, RAM_FOUR_COMMAND_FIELDS),
        ] {
            let mut normal = super::super::tests::fixture(shape);
            let template = &templates::TEMPLATES[shape];
            let at = (template.reference_cpu - 0x410000) as usize;
            let start = at - 6 - grammar.len();
            normal[start..at - 6].copy_from_slice(grammar);
            let initial = bind_at(&normal, shape, template, at).unwrap();
            if let Some(Coefficients::Ram(base)) = initial.coefficients.first() {
                normal[start + fields[0]..start + fields[0] + 4]
                    .copy_from_slice(&(base - 38).to_be_bytes());
            }
            let mut binding = initial.clone();
            bind(&normal, &mut binding).unwrap();
            assert!(binding.complete_command);
            assert_eq!(binding.command, Some(start..at - 6));
            normal[start + fields[2] + 3] ^= 1;
            assert_eq!(
                bind(&normal, &mut initial.clone()),
                Err(Error::ResourceMismatch)
            );
            normal[start + fields[2] + 3] ^= 1;
            normal[at - 8] ^= 1;
            assert_eq!(bind(&normal, &mut initial.clone()), Err(Error::Unresolved));
        }
    }
}
