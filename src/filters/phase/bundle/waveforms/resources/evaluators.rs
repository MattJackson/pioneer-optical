/// Native source of the eight signed evaluator calibration values.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Calibration {
    /// Values returned directly from image immediates, indexed by mode 0..7.
    Constants([i16; 8]),
    /// Native parameter calls with an erased-word fallback. The call bodies
    /// must be proved by the final mechanism owner; this records their wiring.
    Parameters {
        /// Parameter indices requested by each mode.
        indices: [u16; 8],
        /// Values used only when the native read returns 0xffff.
        defaults: [i16; 8],
        /// Native context provider and parameter getter entry points.
        helpers: [u32; 2],
    },
}

/// Bind the complete calibration getter called by the evaluators.
pub fn calibration(normal: &[u8], binding: &Binding) -> Result<(Range<usize>, Calibration), Error> {
    calibration_at(normal, binding.calibration_getter)
}

/// Bind the same native eight-mode getter at a positively bound consumer call.
/// This establishes the getter program and its source operands; parameter helper
/// bodies and resident arithmetic remain separate contracts.
pub fn calibration_at(normal: &[u8], address: u32) -> Result<(Range<usize>, Calibration), Error> {
    let at = address.checked_sub(0x410000).ok_or(Error::Unresolved)? as usize;
    let read = |body: &[u8], offset| u16::from_be_bytes([body[offset], body[offset + 1]]);
    for shape in [CONSTANT_CALIBRATION, PARAMETER_CALIBRATION] {
        let Some(body) = normal.get(at..at + shape.len()) else {
            continue;
        };
        if !body
            .iter()
            .zip(shape)
            .all(|(byte, expected)| expected.map_or(true, |expected| *byte == expected))
        {
            continue;
        }
        let program = table(normal, address, shape.len())?;
        if shape.len() == CONSTANT_CALIBRATION.len() {
            return Ok((
                program,
                Calibration::Constants(
                    [74, 68, 62, 56, 74, 50, 44, 34].map(|offset| read(body, offset) as i16),
                ),
            ));
        }
        let context = [241, 215, 189, 163, 135, 105, 75, 45].map(|offset| call(body, offset));
        let getter = [249, 223, 197, 171, 143, 113, 83, 53].map(|offset| call(body, offset));
        if context.iter().any(|address| *address != context[0])
            || getter.iter().any(|address| *address != getter[0])
            || context[0] == getter[0]
            || [71, 101, 131]
                .into_iter()
                .any(|offset| call(body, offset) != address + 264)
        {
            return Err(Error::ResourceMismatch);
        }
        return Ok((
            program,
            Calibration::Parameters {
                indices: [246, 220, 194, 168, 140, 110, 80, 50].map(|offset| read(body, offset)),
                defaults: [262, 236, 210, 184, 158, 128, 98, 68]
                    .map(|offset| read(body, offset) as i16),
                helpers: [context[0], getter[0]],
            },
        ));
    }
    Err(Error::Unresolved)
}

/// Replace only the bound 64-row image basis. The target's complete generation,
/// scale, clipping and calibration programs remain byte-identical. This stage
/// does not establish full phase equivalence or finalize image integrity.
pub fn rewrite_basis(target: &[u8], installed: &[u8]) -> Result<Vec<u8>, Error> {
    let target_binding = observe(target)?;
    let installed_binding = observe(installed)?;
    let (calibration_program, _) = calibration(target, &target_binding)?;
    let producer = software::observe_producer(target)?;
    let consumer = software::observe(target)?;
    let mut protected = target_binding.programs.clone();
    protected.extend([
        calibration_program,
        producer.program,
        producer.initializer,
        consumer.dispatch,
        consumer.selector,
    ]);
    if protected.iter().any(|range| {
        range.start < target_binding.basis.end && target_binding.basis.start < range.end
    }) {
        return Err(Error::ResourceMismatch);
    }
    let mut changed = target.to_vec();
    changed[target_binding.basis.clone()].copy_from_slice(&installed[installed_binding.basis]);
    if observe(&changed)? != target_binding
        || calibration(&changed, &target_binding)? != calibration(target, &target_binding)?
    {
        return Err(Error::ResourceMismatch);
    }
    Ok(changed)
}
