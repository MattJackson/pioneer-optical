fn candidate(normal: &[u8], binding: &Binding, at: usize) -> Result<Generated, Error> {
    let producer = stored(normal, 0x410000 + at as u32, CODE.len())?;
    let code = &normal[producer.clone()];
    if !code.iter().zip(CODE).enumerate().all(|(i, (a, b))| {
        a == b
            || FIELDS
                .iter()
                .any(|(at, width, _)| (*at..*at + *width).contains(&i))
    }) {
        return Err(Error::Unresolved);
    }
    let mut roles: Vec<(u32, u32)> = Vec::new();
    for &(offset, width, reference) in FIELDS {
        let value = integer(&code[offset..offset + width]);
        if let Some((_, old)) = roles.iter().find(|(key, _)| *key == reference) {
            if *old != value {
                return Err(Error::ResourceMismatch);
            }
        } else {
            roles.push((reference, value));
        }
        if (REFERENCE..REFERENCE + CODE.len() as u32).contains(&reference)
            && value != 0x410000 + at as u32 + reference - REFERENCE
        {
            return Err(Error::ResourceMismatch);
        }
    }
    let role = |reference| {
        roles
            .iter()
            .find(|(key, _)| *key == reference)
            .map(|(_, v)| *v)
            .ok_or(Error::ResourceMismatch)
    };
    for (reference, table) in [0x4312, 0x4392, 0x4412, 0x4492]
        .into_iter()
        .zip(&binding.coefficients)
    {
        if *table != Coefficients::Ram(role(reference)?) {
            return Err(Error::ResourceMismatch);
        }
    }
    let evaluators =
        shared::observe_evaluators(normal, role(0x57a334)?, role(0x57a438)?, role(0x57a24a)?)?;
    if evaluators.precision != shared::Precision::Byte
        || evaluators.basis.start as u32 + 0x410000 != role(0x624b20)?
        || evaluators.arithmetic != [role(0x405a14)?, role(0x4059b2)?]
    {
        return Err(Error::ResourceMismatch);
    }
    let logger = role(0x40405a)?;
    if !(0x400000..0x410000).contains(&logger) || logger & 1 != 0 {
        return Err(Error::ResourceMismatch);
    }
    let mut messages = Vec::new();
    for (reference, text) in [
        (0x5fc94a, b"SL1+:%02xh\n\0"),
        (0x5fc956, b"SL1-:%02xh\n\0"),
        (0x5fc962, b"SL2+:%02xh\n\0"),
        (0x5fc96e, b"SL2-:%02xh\n\0"),
    ] {
        let r = stored(normal, role(reference)?, text.len())?;
        if normal[r.clone()] != *text {
            return Err(Error::ResourceMismatch);
        }
        messages.push(r);
    }
    let messages: [Range<usize>; 4] = messages.try_into().map_err(|_| Error::ResourceMismatch)?;
    let mut all = alloc::vec![
        producer.clone(),
        binding.body.clone(),
        evaluators.calibration.clone(),
        evaluators.basis.clone()
    ];
    all.extend(evaluators.programs.iter().cloned());
    all.extend(messages.iter().cloned());
    if let Some(command) = &binding.command {
        all.push(command.clone());
    }
    if let Some(leaf) = &binding.output_leaf {
        all.push(leaf.clone());
    }
    for (i, a) in all.iter().enumerate() {
        if all[i + 1..].iter().any(|b| overlaps(a, b)) {
            return Err(Error::ResourceMismatch);
        }
    }
    Ok(Generated {
        producer,
        calibration: evaluators.calibration.clone(),
        basis: evaluators.basis.clone(),
        arithmetic: [evaluators.arithmetic[1], evaluators.arithmetic[0]],
        calibration_reader: evaluators.parameter_reader,
        evaluators: Some(evaluators),
        logger,
        messages,
    })
}

pub(super) fn observe(normal: &[u8], binding: &Binding) -> Result<Generated, Error> {
    if binding.shape != 8 || !binding.complete_command || binding.coefficients.len() != 4 {
        return Err(Error::Unresolved);
    }
    let regions = crate::image::regions(normal).ok_or(Error::Unresolved)?;
    let prefix: Vec<_> = CODE[..16].iter().copied().map(Some).collect();
    let mut result = None;
    for at in crate::filters::phase::bundle::sites(normal, &regions.stored, &prefix) {
        if let Ok(found) = candidate(normal, binding, at) {
            if result.as_ref().is_some_and(|old| *old != found) {
                return Err(Error::Unresolved);
            }
            result = Some(found);
        }
    }
    result.ok_or(Error::Unresolved)
}

