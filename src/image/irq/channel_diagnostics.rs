fn matches(
    n: &Native<'_>,
    at: usize,
    template: &[u8],
    holes: &[(usize, usize, Kind)],
) -> Option<()> {
    let b = n.get(at, template.len())?;
    for i in 0..b.len() {
        if !holes.iter().any(|&(a, z, _)| (a..z).contains(&i)) && b[i] != template[i] {
            return None;
        }
    }
    for (i, &(a, z, kind)) in holes.iter().enumerate() {
        let value = super::super::number(&b[a..z]);
        match kind {
            Ram => {
                if value >= 0x8000 {
                    return None;
                }
            }
            Call => {
                cpu(n, &b[a..z])?;
            }
            Stored => {
                let offset = value.checked_sub(0x410000)? as usize;
                n.get(offset, 8)?;
            }
            Buffer => {
                if !(0xa00000..0xb00000).contains(&value) {
                    return None;
                }
            }
            Limit => {
                if !(0x900001..=0xa00000).contains(&value) {
                    return None;
                }
            }
        }
        // Preserve all repeated and distinct operands within each native role.
        for &(pa, pz, pk) in &holes[..i] {
            if pk == kind && (template[pa..pz] == template[a..z]) != (b[pa..pz] == b[a..z]) {
                return None;
            }
        }
    }
    Some(())
}
pub(super) fn bind(
    n: &Native<'_>,
    at: usize,
    identifiers: [u32; 2],
) -> Option<Vec<(usize, usize)>> {
    matches(n, at, WRAPPER, WRAPPER_HOLES)?;
    let body = call(n, at + 56)?;
    matches(n, body, BODY, BODY_HOLES)?;
    let b = n.get(body, BODY.len())?;
    let number = super::super::number;
    let upper = number(&b[0x11e..0x122]);
    if identifiers[0] == identifiers[1]
        || identifiers
            .iter()
            .any(|&id| !(0x900000..upper).contains(&id))
    {
        return None;
    }
    let flag = number(n.get(at + 8, 4)?);
    if flag.checked_add(4)? != number(&b[0x1e..0x22]) || number(&b[0x1d8..0x1dc]) != flag + 5 {
        return None;
    }
    let data = number(&b[0x36..0x3a]).checked_sub(0x410000)? as usize;
    Some(vec![(at, WRAPPER.len()), (body, BODY.len()), (data, 8)])
}
