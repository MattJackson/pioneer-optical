//! Native DSP-loader and subsequent movement-mode coherence.
//!
//! The contract starts at the loader call, not at controller entry: the actual
//! R6L value supplied to the loader must also become the movement object's
//! direction byte. Earlier initialization calls are outside this proof.
use super::*;

/// A native mode-coherence graph could not be established.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Failure {
    /// A complete native graph is missing or ambiguous.
    Unresolved,
    /// A graph operand disagrees with its native consumer.
    Relationship,
    /// An external entry can bypass the bound mode preparation.
    References,
}

/// Positively bound local mode graph. All ranges are Normal file offsets.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Binding {
    /// Complete native DSP loader.
    pub loader: Range<usize>,
    /// R6L-to-loader preparation through the subsequent movement call.
    pub coherence: Range<usize>,
    /// Complete intervening DSP control routine, preserving ER4..ER6.
    pub control: Range<usize>,
    /// Complete intervening state setter, using only R0/ER0.
    pub setter: Range<usize>,
    /// Complete movement constructor storing its direction at object offset six.
    pub movement: Range<usize>,
    /// Complete native movement callback consuming that direction.
    pub tick: Range<usize>,
    /// Native callback object's stored vtable through its direction callback.
    pub vtable: Range<usize>,
}

/// Source and destination use the same actual zero/nonzero movement mode.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Proof {
    /// Destination computed-loader mode graph.
    pub target: Binding,
    /// Source plain-loader mode graph.
    pub donor: Binding,
}
fn stored(n: &[u8], address: u32, size: usize) -> Result<Range<usize>, Failure> {
    let start = address.checked_sub(0x410000).ok_or(Failure::Relationship)? as usize;
    let end = start.checked_add(size).ok_or(Failure::Relationship)?;
    let regions = crate::image::regions(n).ok_or(Failure::Unresolved)?;
    if start & 1 != 0
        || !regions.stored.iter().any(|r| {
            let at = r.as_ptr() as usize - n.as_ptr() as usize;
            at <= start && end <= at + r.len()
        })
    {
        return Err(Failure::Relationship);
    }
    Ok(start..end)
}
fn matched(n: &[u8], address: u32, shape: Template) -> Result<Range<usize>, Failure> {
    let span = stored(n, address, shape.len())?;
    if !n[span.clone()]
        .iter()
        .zip(shape)
        .all(|(actual, expected)| expected.map_or(true, |v| *actual == v))
    {
        return Err(Failure::Unresolved);
    }
    Ok(span)
}

/// Bind every visible loader entry to a native direction-coherent movement.
///
/// The two intervening complete native helpers either save and restore ER6 or
/// never write it. Their DSP calls bind to the loader's existing writer/reader.
/// The complete movement routine stores R1L at object[6] before any helper call;
/// its bound vtable callback selects positive/negative row delta from that byte.
/// Ordinary native call/return stack discipline is the same precondition as the
/// existing native loader proofs. This does not claim entry-R1H preservation,
/// callback scheduling, or that an image lacking this graph has equivalent DSP.
pub fn observe(n: &[u8], kernel: &[u8]) -> Result<Binding, Failure> {
    let loader = loader::observe(n).map_err(|_| Failure::Unresolved)?;
    if loader.spans.len() != 1 {
        return Err(Failure::Unresolved);
    }
    let regions = crate::image::regions(n).ok_or(Failure::Unresolved)?;
    let mut candidates = Vec::new();
    for shape in [COHERENCE_UD, COHERENCE_BD] {
        for at in sites(n, &regions.stored, shape) {
            if call(&n[at..], 3) == 0x410000 + loader.program.start as u32 {
                candidates.push(at..at + shape.len());
            }
        }
    }
    let [coherence] = candidates.as_slice() else {
        return Err(Failure::Unresolved);
    };
    let body = &n[coherence.clone()];
    let control_address = call(body, 9);
    let mut controls = Vec::new();
    for (shape, writers) in [(CONTROL_UD, [44, 146]), (CONTROL_BD, [46, 148])] {
        if let Ok(span) = matched(n, control_address, shape) {
            let bytes = &n[span.clone()];
            if word(bytes, 10) == loader.readback
                && writers.iter().all(|at| word(bytes, *at) == loader.writer)
            {
                controls.push(span);
            }
        }
    }
    let [control] = controls.as_slice() else {
        return Err(Failure::Relationship);
    };
    loader::readback::observe(n, loader.readback, loader.writer)
        .map_err(|_| Failure::Relationship)?;
    let setter = matched(n, call(body, 31), SETTER)?;
    let movement = matched(n, call(body, 49), MOVE)?;
    let vtable = stored(n, word(body, 16), 20)?;
    let tick = matched(n, word(&n[vtable.clone()], 16), TICK)?;
    let set = &n[setter.clone()];
    let mov = &n[movement.clone()];
    let tick_body = &n[tick.clone()];
    if word(set, 2) != word(mov, 40)
        || word(set, 8) != word(mov, 190)
        || word(set, 2) != word(tick_body, 12)
        || word(set, 2) != word(tick_body, 40)
        || word(mov, 26) != call(tick_body, 7)
        || call(mov, 99) != call(mov, 159)
        || call(mov, 99) != call(tick_body, 31)
        || word(mov, 88) != word(mov, 108)
        || word(mov, 88) != word(mov, 148)
        || call(mov, 61) != call(mov, 117)
    {
        return Err(Failure::Relationship);
    }
    // The getter preserves ER3, which carries the callback object's address.
    // Its initializer may clobber scratch registers; the saved ER3 is restored.
    let getter = matched(n, word(mov, 26), GETTER)?;
    let g = &n[getter.clone()];
    if word(g, 12) != word(g, 24) {
        return Err(Failure::Relationship);
    }
    // No other loader entry, raw pointer, relative branch, or Kernel reference
    // may bypass this complete loader-to-movement mode sequence.
    let replaced = [loader.program.clone(), coherence.clone()];
    let known = [
        loader.program.clone(),
        coherence.clone(),
        control.clone(),
        setter.clone(),
        movement.clone(),
        tick.clone(),
    ];
    retirement::references_clear(
        n,
        kernel,
        &[loader.program.clone(), coherence.start + 1..coherence.end],
        &replaced,
        &known,
    )
    .ok_or(Failure::References)?;
    Ok(Binding {
        loader: loader.program,
        coherence: coherence.clone(),
        control: control.clone(),
        setter,
        movement,
        tick,
        vtable,
    })
}

/// Discharge the entry-mode obligation of `coefficient_bridge::transplant_plain`.
/// Both exact associated Kernels are mandatory. The transplanted plain loader
/// must retain its independently proved ER6 preservation and native table order.
/// This proof authorizes no table allocation or software-only reverse route.
pub fn prove_plain_transplant(
    target: &[u8],
    donor: &[u8],
    target_kernel: &[u8],
    donor_kernel: &[u8],
) -> Result<Proof, Failure> {
    if !loader::observe(target)
        .map_err(|_| Failure::Unresolved)?
        .computed
        || loader::observe(donor)
            .map_err(|_| Failure::Unresolved)?
            .computed
    {
        return Err(Failure::Relationship);
    }
    Ok(Proof {
        target: observe(target, target_kernel)?,
        donor: observe(donor, donor_kernel)?,
    })
}
