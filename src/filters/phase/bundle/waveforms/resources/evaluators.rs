/// Native coefficient basis and evaluator wiring, without calibration-source
/// equivalence or whole-mechanism correction claims.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Binding {
    /// Image basis containing 64 paired signed coefficients.
    pub basis: Range<usize>,
    /// Complete evaluator bodies (one shared or two separate functions).
    pub programs: Vec<Range<usize>>,
    /// Target calibration getter retained by any basis-only transformation.
    pub calibration_getter: u32,
    /// Native signed multiplication and division helpers, in that order.
    pub arithmetic: [u32; 2],
}

fn bind_body(
    normal: &[u8],
    at: usize,
    shape: Template,
    data: usize,
    jump: usize,
    calls: [usize; 12],
) -> Result<Binding, Error> {
    let body = normal.get(at..at + shape.len()).ok_or(Error::Unresolved)?;
    if !body
        .iter()
        .zip(shape)
        .all(|(byte, expected)| expected.map_or(true, |expected| *byte == expected))
    {
        return Err(Error::Unresolved);
    }
    if call(body, jump) != 0x410000 + (at + shape.len() - 6) as u32 {
        return Err(Error::ResourceMismatch);
    }
    let addresses = calls.map(|field| call(body, field));
    let multiply = addresses[0];
    let divide = addresses[1];
    let calibration = addresses[4];
    if [0, 2, 6, 10].into_iter().any(|i| addresses[i] != multiply)
        || [1, 3, 7, 11].into_iter().any(|i| addresses[i] != divide)
        || [4, 5, 8, 9]
            .into_iter()
            .any(|i| addresses[i] != calibration)
        || multiply == divide
        || multiply == calibration
        || divide == calibration
    {
        return Err(Error::ResourceMismatch);
    }
    table(normal, calibration, 2)?;
    let basis = table(normal, word(body, data), 256)?;
    if basis.start < at + shape.len() && at < basis.end {
        return Err(Error::ResourceMismatch);
    }
    Ok(Binding {
        basis,
        programs: alloc::vec![at..at + shape.len()],
        calibration_getter: calibration,
        arithmetic: [multiply, divide],
    })
}

/// Follow the bound producer's channel calls into complete native evaluators.
pub fn observe(normal: &[u8]) -> Result<Binding, Error> {
    let producer = software::observe_producer(normal)?;
    let [first, second] = producer
        .evaluators
        .map(|address| address.checked_sub(0x410000).map(|at| at as usize));
    let (Some(first), Some(second)) = (first, second) else {
        return Err(Error::Unresolved);
    };
    // The shared form's two complete wrappers pass channel zero/one and branch
    // to the same body. Their relative branches establish the local linkage.
    if second == first + 8
        && normal.get(first..first + 16)
            == Some(&[
                0x0c, 0x80, 0x18, 0x88, 0x55, 0x0a, 0x54, 0x70, 0x0c, 0x80, 0xf8, 0x01, 0x55, 0x02,
                0x54, 0x70,
            ])
    {
        let mut binding = bind_body(
            normal,
            first + 16,
            SHARED,
            28,
            43,
            [59, 67, 75, 83, 103, 119, 137, 149, 175, 191, 209, 223],
        )?;
        binding.programs.insert(0, first..first + 16);
        return Ok(binding);
    }
    let mut a = bind_body(
        normal,
        first,
        FIRST,
        18,
        33,
        [49, 57, 65, 73, 85, 93, 115, 127, 145, 153, 175, 189],
    )?;
    let b = bind_body(
        normal,
        second,
        SECOND,
        18,
        35,
        [53, 61, 69, 77, 89, 97, 119, 131, 149, 157, 179, 193],
    )?;
    if a.basis != b.basis
        || a.calibration_getter != b.calibration_getter
        || a.arithmetic != b.arithmetic
        || (a.programs[0].start < b.programs[0].end && b.programs[0].start < a.programs[0].end)
    {
        return Err(Error::ResourceMismatch);
    }
    a.programs.extend(b.programs);
    Ok(a)
}

