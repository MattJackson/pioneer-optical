#[test]
fn captured_indirect_entry_requires_the_kernel_exports() {
    let (normal, kernel) = fixture();
    assert_eq!(receiver_control(&normal), None);
    assert_eq!(
        receiver_control_with_kernel(&normal, Some(&kernel)),
        Some(ReceiverControl::DescriptorOnly)
    );
    for address in [0x400a14, 0x400a1a, 0x400465, 0x400477, 0x400a04, 0x400100] {
        let mut changed = kernel.clone();
        changed[address - KERNEL_BASE as usize] ^= 1;
        assert_eq!(
            receiver_control_with_kernel(&normal, Some(&changed)),
            None,
            "Kernel {address:x}"
        );
    }
}

#[test]
fn changed_descriptor_loop_and_helper_graph_fail_closed() {
    let (normal, kernel) = fixture();
    for address in [
        0x44bfe0, 0x44bff0, 0x44bff3, 0x44bff9, 0x44bffb, 0x44bfff, 0x44c007, 0x44c00b, 0x43ec45,
        0x4b0891, 0x4ad55f, 0x4ad56b, 0x4ad591, 0x4ad599, 0x4ad53b, 0x456c33, 0x44c423, 0x44c48f,
    ] {
        let mut changed = normal.clone();
        changed[address - BASE as usize] ^= 1;
        assert_eq!(
            receiver_control_with_kernel(&changed, Some(&kernel)),
            None,
            "Normal {address:x}"
        );
    }
    let mut changed = normal.clone();
    changed[0x44bfea - BASE as usize..0x44bfee - BASE as usize]
        .copy_from_slice(&[0x5e, 0xff, 0xff, 0xfe]);
    assert_eq!(receiver_control_with_kernel(&changed, Some(&kernel)), None);
    assert_eq!(
        receiver_control_with_kernel(&normal, Some(&kernel[..0x400])),
        None
    );
}

#[test]
fn indirect_and_keyed_entry_are_ambiguous() {
    let (mut normal, kernel) = fixture();
    normal.extend_from_slice(&[
        0x7a, 0x20, 0x9a, 0x78, 0x23, 0x61, 0x47, 8, 0x7a, 0x20, 1, 2, 3, 4, 0x46, 0x4e,
    ]);
    assert_eq!(receiver_control_with_kernel(&normal, Some(&kernel)), None);
}

#[test]
#[ignore = "set PIONEER_L12SH_CAPTURE and PIONEER_L13SH_CAPTURE to Kernel+Normal captures"]
fn supplied_l12sh_and_l13sh_captures_when_configured() {
    for name in ["PIONEER_L12SH_CAPTURE", "PIONEER_L13SH_CAPTURE"] {
        let path = std::env::var_os(name).expect(name);
        let bytes = std::fs::read(path).unwrap();
        let (kernel, normal) = bytes.split_at(KERNEL_LEN);
        assert_eq!(
            receiver_control_with_kernel(normal, Some(kernel)),
            Some(ReceiverControl::DescriptorOnly),
            "{name}"
        );
    }
}
