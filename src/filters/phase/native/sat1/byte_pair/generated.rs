/// Coherent resource binding of a calibrated byte generator.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Generated {
    /// Separate exact byte-precision evaluators for the four-bank mechanism;
    /// the three-bank mechanism inlines its arithmetic in the producer.
    pub evaluators: Option<shared::Evaluators>,
    /// Native table-production body (all loops and side effects retained).
    pub producer: Range<usize>,
    /// Eight-slot calibrated-value getter with native fallback constants.
    pub calibration: Range<usize>,
    /// Interleaved 64-phase, two-word basis used by every production loop.
    pub basis: Range<usize>,
    /// Target division and multiplication helper entry points, in that order.
    pub arithmetic: [u32; 2],
    /// Target persistent calibration reader, not a donor device's calibration.
    pub calibration_reader: u32,
    /// Target diagnostic sink used by the native generator.
    pub logger: u32,
    /// Four native diagnostic strings, checked in full.
    pub messages: [Range<usize>; 4],
}

fn candidate(normal: &[u8], binding: &Binding, at: usize) -> Result<Generated, Error> {
    let range = stored(normal, 0x410000 + at as u32, CODE.len())?;
    let code = &normal[range.clone()];
    if !code.iter().zip(CODE).enumerate().all(|(i, (a, b))| {
        a == b
            || FIELDS
                .iter()
                .any(|(at, width, _)| (*at..*at + *width).contains(&i))
    }) {
        return Err(Error::Unresolved);
    }
    let mut roles: Vec<(u32, u32)> = Vec::new();
    for &(offset, width, reference) in FIELDS {
        let value = integer(&code[offset..offset + width]);
        if let Some((_, old)) = roles.iter().find(|(key, _)| *key == reference) {
            if value != *old {
                return Err(Error::ResourceMismatch);
            }
        } else {
            roles.push((reference, value));
        }
        if (REFERENCE..REFERENCE + CODE.len() as u32).contains(&reference)
            && value != 0x410000 + at as u32 + (reference - REFERENCE)
        {
            return Err(Error::ResourceMismatch);
        }
    }
    let role = |reference| {
        roles
            .iter()
            .find(|(key, _)| *key == reference)
            .map(|(_, value)| *value)
            .ok_or(Error::ResourceMismatch)
    };
    for (reference, table) in [0x432c, 0x43ac, 0x442c]
        .into_iter()
        .zip(&binding.coefficients)
    {
        if *table != Coefficients::Ram(role(reference)?) {
            return Err(Error::ResourceMismatch);
        }
    }
    let arithmetic = [role(0x4056f4)?, role(0x405756)?];
    let logger = role(0x403da4)?;
    if arithmetic
        .into_iter()
        .chain([logger])
        .any(|a| !(0x400000..0x410000).contains(&a) || a & 1 != 0)
        || arithmetic[0] == arithmetic[1]
    {
        return Err(Error::ResourceMismatch);
    }
    let calibration_reader = role(0x46de38)?;
    stored(normal, calibration_reader, 2)?;
    let basis = stored(normal, role(0x6153b2)?, 256)?;
    let mut messages = Vec::new();
    for (reference, text) in [
        (0x5f5246, b"SL1+:%02xh\n\0"),
        (0x5f5252, b"SL1-:%02xh\n\0"),
        (0x5f525e, b"SL2+:%02xh\n\0"),
        (0x5f526a, b"SL2-:%02xh\n\0"),
    ] {
        let r = stored(normal, role(reference)?, text.len())?;
        if normal[r.clone()] != *text {
            return Err(Error::ResourceMismatch);
        }
        messages.push(r);
    }
    let messages: [Range<usize>; 4] = messages.try_into().map_err(|_| Error::ResourceMismatch)?;
    let mut all = alloc::vec![range.clone(), binding.body.clone(), basis.clone()];
    if let Some(command) = &binding.command {
        all.push(command.clone());
    }
    all.extend(messages.iter().cloned());
    for (i, a) in all.iter().enumerate() {
        if all[i + 1..].iter().any(|b| overlaps(a, b)) {
            return Err(Error::ResourceMismatch);
        }
    }
    Ok(Generated {
        evaluators: None,
        calibration: at..at + 234,
        producer: at + 234..range.end,
        basis,
        arithmetic,
        calibration_reader,
        logger,
        messages,
    })
}

/// Observe the complete three- or four-bank producer graph and all resource
/// operands. This is not permission to replace the calibration reader or logger.
pub fn observe(normal: &[u8], binding: &Binding) -> Result<Generated, Error> {
    if binding.shape == 8 {
        return four::observe(normal, binding);
    }
    if binding.shape != 7 || !binding.complete_command || binding.coefficients.len() != 3 {
        return Err(Error::Unresolved);
    }
    let regions = crate::image::regions(normal).ok_or(Error::Unresolved)?;
    let prefix: Vec<_> = CODE[..16].iter().copied().map(Some).collect();
    let mut result = None;
    for at in crate::filters::phase::bundle::sites(normal, &regions.stored, &prefix) {
        if let Ok(found) = candidate(normal, binding, at) {
            if result.as_ref().is_some_and(|old| *old != found) {
                return Err(Error::Unresolved);
            }
            result = Some(found);
        }
    }
    result.ok_or(Error::Unresolved)
}

/// Additionally establish both arithmetic services from the authoritative Kernel.
/// The complete logical persistent-word contract is also validated. Physical
/// banks and the diagnostic sink stay target-owned; neither is replaced.
pub fn observe_with_kernel(
    normal: &[u8],
    kernel: &[u8],
    binding: &Binding,
) -> Result<
    (
        Generated,
        crate::filters::phase::native::arithmetic::Binding,
    ),
    Error,
> {
    if kernel.len() != crate::image::KERNEL_LEN {
        return Err(Error::ResourceMismatch);
    }
    let graph = observe(normal, binding)?;
    let arithmetic = crate::filters::phase::native::arithmetic::observe(
        kernel,
        0x400000,
        graph.arithmetic[1],
        graph.arithmetic[0],
    )
    .ok_or(Error::ResourceMismatch)?;
    parameter_contract(normal, Some(kernel), &graph)?;
    Ok((graph, arithmetic))
}

/// Establish the native logical word-index and erased-word fallback contract.
/// Physical banks and journal layout stay with the persistent-layout owner.
pub fn parameter_contract(
    normal: &[u8],
    kernel: Option<&[u8]>,
    graph: &Generated,
) -> Result<shared::ParameterContract, Error> {
    let address = u32::try_from(graph.calibration.start)
        .ok()
        .and_then(|at| 0x410000u32.checked_add(at))
        .ok_or(Error::ResourceMismatch)?;
    shared::parameter_contract_at(normal, kernel, address)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn byte_pair_ram_producer_binds_repeated_resources_and_rejects_detachment() {
        let mut normal = alloc::vec![255; 0x210000];
        let at = (REFERENCE - 0x410000) as usize;
        normal[at..at + CODE.len()].copy_from_slice(CODE);
        for (addr, text) in [
            (0x5f5246, b"SL1+:%02xh\n\0"),
            (0x5f5252, b"SL1-:%02xh\n\0"),
            (0x5f525e, b"SL2+:%02xh\n\0"),
            (0x5f526a, b"SL2-:%02xh\n\0"),
        ] {
            let start = addr - 0x410000;
            normal[start..start + text.len()].copy_from_slice(text);
        }
        let binding = Binding {
            shape: 7,
            body: 0x1000..0x1076,
            command: None,
            complete_command: true,
            coefficients: alloc::vec![
                Coefficients::Ram(0x432c),
                Coefficients::Ram(0x43ac),
                Coefficients::Ram(0x442c)
            ],
            state: alloc::vec![],
            output_leaf: None,
        };
        let result = observe(&normal, &binding).unwrap();
        assert_eq!(result.arithmetic, [0x4056f4, 0x405756]);
        assert_eq!(result.producer.len(), 1682);
        let &(offset, width, _) = FIELDS
            .iter()
            .find(|(_, _, reference)| *reference == 0x405756)
            .unwrap();
        normal[at + offset + width - 1] ^= 2;
        assert_eq!(observe(&normal, &binding), Err(Error::Unresolved));
        normal[at + offset + width - 1] ^= 2;
        normal[at + 250] ^= 1;
        assert_eq!(observe(&normal, &binding), Err(Error::Unresolved));
    }
}
